create or replace function set_updated_at()
returns trigger language plpgsql as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists sites_set_updated_at on sites;
create trigger sites_set_updated_at before update on sites
for each row execute function set_updated_at();

drop trigger if exists notes_set_updated_at on notes;
create trigger notes_set_updated_at before update on notes
for each row execute function set_updated_at();

drop trigger if exists notes_content_set_updated_at on notes_content;
create trigger notes_content_set_updated_at before update on notes_content
for each row execute function set_updated_at();

create or replace function refresh_notebook_note_count()
returns trigger language plpgsql as $$
begin
  update notebooks
     set note_count = (select count(*) from notes_content where notebook_id = coalesce(new.notebook_id, old.notebook_id))
   where id = coalesce(new.notebook_id, old.notebook_id);
  return null;
end;
$$;

drop trigger if exists notes_content_refresh_count on notes_content;
create trigger notes_content_refresh_count
after insert or delete or update of notebook_id on notes_content
for each row execute function refresh_notebook_note_count();
