create extension if not exists pgcrypto;
create extension if not exists citext;

create table if not exists technicians (
  id uuid primary key default gen_random_uuid(),
  code citext not null unique,
  name text not null default '',
  role text not null default 'tech' check (role in ('tech', 'admin')),
  zone text,
  active boolean not null default true,
  avatar_url text,
  last_login timestamptz,
  created_at timestamptz not null default now()
);

create table if not exists technician_credentials (
  technician_id uuid primary key references technicians(id) on delete cascade,
  pin_hash text,
  legacy_pin text,
  updated_at timestamptz not null default now(),
  check (pin_hash is not null or legacy_pin is not null)
);

create table if not exists sessions (
  id uuid primary key default gen_random_uuid(),
  technician_id uuid not null references technicians(id) on delete cascade,
  token_hash char(64) not null unique,
